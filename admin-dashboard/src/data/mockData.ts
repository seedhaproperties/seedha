export function getDisplayStatusLabel(req: PropertyRequest): string {
  if (req.status === 'published') {
    if (req.module === 'home_loan') return 'Approved';
    if (req.module === 'rental_agreements') return 'Delivered';
    if (req.module === 'owner_background') return 'Sent Digitally';
    if (req.module === 'property_management') return 'Onboarded';
    if (req.postPublishState === 'rented') return 'Rented';
    if (req.postPublishState === 'sold') return 'Sold';
    if (req.postPublishState === 'archived') return 'Archived';
    if (req.postPublishState === 'unpublished') return 'Unpublished';
    return 'Published';
  }
  if (req.status === 'field_visit') {
    if (req.module === 'home_loan') return 'Contacted';
    if (req.module === 'rental_agreements') return 'Docs Prep';
    if (req.module === 'property_management') return 'Location Check';
  }
  return STATUS_CONFIG[req.status].label;
}
