import { Test, TestingModule } from '@nestjs/testing';
import { INestApplication, ValidationPipe } from '@nestjs/common';
import request from 'supertest';
import { AppModule } from '../src/app.module.js';
import { Msg91Service } from '../src/modules/auth/msg91.service.js';

describe('OTP Modes - Development vs Production Specification Tests', () => {
  let app: INestApplication;
  let msg91Service: Msg91Service;

  beforeAll(async () => {
    // Force development environment
    process.env.NODE_ENV = 'development';

    const moduleFixture: TestingModule = await Test.createTestingModule({
      imports: [AppModule],
    }).compile();

    app = moduleFixture.createNestApplication();
    app.useGlobalPipes(
      new ValidationPipe({
        whitelist: true,
        transform: true,
      }),
    );
    await app.init();

    msg91Service = app.get(Msg91Service);
  });

  afterAll(async () => {
    await app.close();
  });

  describe('Section A: Development OTP Testing Mode (NODE_ENV=development)', () => {
    const devPhone = '+919876543210';
    let accessToken = '';

    it('1. Environment check: Confirms service detects development mode', () => {
      expect(msg91Service.isDevelopment).toBe(true);
      expect(msg91Service.isProduction).toBe(false);
      expect(msg91Service.isMockMode).toBe(true);
    });

    it('2. Send OTP: Dispatches without MSG91 SMS delivery and returns development instruction', async () => {
      const res = await request(app.getHttpServer())
        .post('/api/v1/auth/send-otp')
        .send({ identifier: devPhone })
        .expect(200);

      expect(res.body.success).toBe(true);
      expect(res.body.mobile).toBe(devPhone);
      expect(res.body.message).toContain('Development Mode: Use test OTP 123456');
    });

    it('3. Resend OTP: Works smoothly without MSG91 dependency in development', async () => {
      const res = await request(app.getHttpServer())
        .post('/api/v1/auth/resend-otp')
        .send({ identifier: devPhone })
        .expect(200);

      expect(res.body.success).toBe(true);
      expect(res.body.mobile).toBe(devPhone);
    });

    it('4. Verify OTP: Fixed test OTP 123456 verifies successfully and generates JWT tokens', async () => {
      const res = await request(app.getHttpServer())
        .post('/api/v1/auth/verify-otp')
        .send({ identifier: devPhone, otp: '123456' })
        .expect(200);

      expect(res.body.success).toBe(true);
      expect(res.body.accessToken).toBeDefined();
      expect(res.body.refreshToken).toBeDefined();
      expect(res.body.user).toBeDefined();
      expect(res.body.phone).toBe(devPhone);

      accessToken = res.body.accessToken;
    });

    it('5. Access Dashboard: Authenticated requests succeed with the generated JWT access token', async () => {
      const res = await request(app.getHttpServer())
        .get('/api/v1/auth/me')
        .set('Authorization', `Bearer ${accessToken}`)
        .expect(200);

      expect(res.body.id).toBeDefined();
      expect(res.body.phone).toBe(devPhone);
    });

    it('6. Invalid OTP: Rejects mismatched OTP (e.g. 888888) with 401 Unauthorized in development', async () => {
      // Send OTP first to ensure store has an entry
      await request(app.getHttpServer())
        .post('/api/v1/auth/send-otp')
        .send({ identifier: devPhone })
        .expect(200);

      const res = await request(app.getHttpServer())
        .post('/api/v1/auth/verify-otp')
        .send({ identifier: devPhone, otp: '888888' })
        .expect(401);

      expect(res.body.message).toContain('Invalid verification code');
    });
  });

  describe('Section B: Production Mode Security Guarantees (NODE_ENV=production)', () => {
    it('1. Environment check: isProduction is true when NODE_ENV=production', () => {
      const prevEnv = process.env.NODE_ENV;
      process.env.NODE_ENV = 'production';

      expect(msg91Service.isProduction).toBe(true);
      expect(msg91Service.isDevelopment).toBe(false);
      expect(msg91Service.isMockMode).toBe(false);

      process.env.NODE_ENV = prevEnv;
    });

    it('2. Production security: verifyOtp strictly disallows 123456 development bypass in production', async () => {
      const prevEnv = process.env.NODE_ENV;
      process.env.NODE_ENV = 'production';

      try {
        // In production mode, verifyOtp will attempt to contact MSG91 Verify API with 123456
        // and reject because 123456 is not a valid OTP generated by MSG91
        await expect(msg91Service.verifyOtp('9876543210', '123456')).rejects.toThrow();
      } finally {
        process.env.NODE_ENV = prevEnv;
      }
    }, 15000);
  });

  describe('Section C: Google OAuth 2.0 PKCE & Secure Token Flow', () => {
    it('1. Rejects Google authentication request when no code or token is provided', async () => {
      await request(app.getHttpServer())
        .post('/api/v1/auth/google')
        .send({})
        .expect(400);
    });

    it('2. Securely handles Google PKCE token exchange failure with invalid code', async () => {
      await request(app.getHttpServer())
        .post('/api/v1/auth/google')
        .send({
          code: 'invalid_mock_code',
          codeVerifier: 'invalid_code_verifier_string_at_least_43_characters_long_12345',
          redirectUri: 'https://auth.expo.io',
        })
        .expect(401);
    }, 15000);

    it('3. Successful Google authentication creates/finds user and issues JWT tokens in test environment', async () => {
      const prevEnv = process.env.NODE_ENV;
      process.env.NODE_ENV = 'test';
      try {
        const testEmail = `google_user_${Date.now()}@gmail.com`;
        const res = await request(app.getHttpServer())
          .post('/api/v1/auth/google')
          .send({
            email: testEmail,
            name: 'Google Test User',
          })
          .expect(200);

        expect(res.body.success).toBe(true);
        expect(res.body.user).toBeDefined();
        expect(res.body.user.email).toBe(testEmail);
        expect(res.body.accessToken).toBeDefined();
        expect(res.body.refreshToken).toBeDefined();
      } finally {
        process.env.NODE_ENV = prevEnv;
      }
    });
  });
});
