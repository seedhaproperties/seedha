async function seed() {
  console.log('Seeding properties into Supabase PostgreSQL database...');
  for (const item of propertiesData) {
    const { lat, lng, pincode } = getCoords(item.location, item.city);
    await prisma.property.upsert({
      where: { id: item.id },
      update: {
        title: item.title,
        description: item.description,
        listingType: item.listingType,
        propertyType: item.propertyType,
        status: 'PUBLISHED',
        price: item.price,
        priceLabel: item.priceLabel,
        location: item.location,
        city: item.city,
        area: item.area,
        bedrooms: item.bedrooms,
        bathrooms: item.bathrooms,
        furnishing: item.furnishing,
        parking: item.parking,
        deposit: item.deposit || null,
        maintenance: item.maintenance || null,
        facing: item.facing || null,
        floor: item.floor || null,
        totalFloors: item.totalFloors || null,
        images: item.images,
        amenities: item.amenities,
        verified: item.verified,
        featured: item.featured || false,
        latitude: lat,
        longitude: lng,
        pincode: pincode,
        ownerName: item.ownerName,
        ownerPhone: item.ownerPhone,
        publishedAt: new Date(),
      },
      create: {
        id: item.id,
        title: item.title,
        description: item.description,
        listingType: item.listingType,
        propertyType: item.propertyType,
        status: 'PUBLISHED',
        price: item.price,
        priceLabel: item.priceLabel,
        location: item.location,
        city: item.city,
        area: item.area,
        bedrooms: item.bedrooms,
        bathrooms: item.bathrooms,
        furnishing: item.furnishing,
        parking: item.parking,
        deposit: item.deposit || null,
        maintenance: item.maintenance || null,
        facing: item.facing || null,
        floor: item.floor || null,
        totalFloors: item.totalFloors || null,
        images: item.images,
        amenities: item.amenities,
        verified: item.verified,
        featured: item.featured || false,
        latitude: lat,
        longitude: lng,
        pincode: pincode,
        ownerName: item.ownerName,
        ownerPhone: item.ownerPhone,
        publishedAt: new Date(),
      },
    });
    console.log(`✓ Upserted property: [${item.id}] ${item.title} (${item.listingType}) in ${item.city}`);
  }
  console.log('Seeding completed successfully!');
  process.exit(0);
}

seed().catch((err) => {
  console.error('Seeding error:', err);
  process.exit(1);
});
